class DeepCodeAdapter:
    """
    Backward-compatible session wrapper around PrototypeScaffoldAdapter.
    Retained only to avoid breaking existing /sessions endpoint call sites
    until those are migrated to the CodingAgentAdapter interface.
    """

    def __init__(self):
        self._sessions: Dict[str, DeepCodeSession] = {}
        self._scaffold = PrototypeScaffoldAdapter()

    def create_session(
        self,
        workspace_path: str,
        model: str = "google/gemma-4-31b-it",
        connection_id: Optional[str] = None,
        access_level: str = "full-access",
        session_id: Optional[str] = None,
        user_id: Optional[str] = None,
        project_id: Optional[str] = None,
    ) -> DeepCodeSession:
        resolved_session_id = session_id or f"dc-sess-{uuid.uuid4().hex[:8]}"
        existing = self._sessions.get(resolved_session_id)
        if existing:
            if existing.user_id and user_id and existing.user_id != user_id:
                raise ValueError("Build session belongs to another user")
            existing.workspace_path = workspace_path
            existing.user_id = existing.user_id or user_id
            existing.project_id = existing.project_id or project_id
            existing.model = model
            existing.connection_id = connection_id
            existing.access_level = access_level
            existing.updated_at = datetime.utcnow().isoformat()
            return existing

        session = DeepCodeSession(
            session_id=resolved_session_id,
            workspace_path=workspace_path,
            user_id=user_id,
            project_id=project_id,
            model=model,
            connection_id=connection_id,
            access_level=access_level,
            status="idle",
        )
        self._sessions[resolved_session_id] = session
        logger.info("Created scaffold session %s", resolved_session_id)
        return session

    def get_session(self, session_id: str) -> Optional[DeepCodeSession]:
        return self._sessions.get(session_id)

    def ensure_session(
        self,
        session_id: str,
        workspace_path: str,
        model: str = "google/gemma-4-31b-it",
        connection_id: Optional[str] = None,
        access_level: str = "full-access",
        user_id: Optional[str] = None,
        project_id: Optional[str] = None,
    ) -> DeepCodeSession:
        return self.create_session(
            workspace_path=workspace_path,
            model=model,
            connection_id=connection_id,
            access_level=access_level,
            session_id=session_id,
            user_id=user_id,
            project_id=project_id,
        )

    async def run_turn(
        self,
        session_id: str,
        prompt: str,
    ) -> AsyncGenerator[DeepCodeEvent, None]:
        session = self._sessions.get(session_id)
        if not session:
            raise ValueError(f"Session {session_id} not found")

        session.status = "running"
        session.updated_at = datetime.utcnow().isoformat()

        spec = BuildSpec(
            run_id=f"legacy-{session_id}",
            project_id=session.project_id or "",
            specification=prompt,
            workspace_path=session.workspace_path,
            approved_by=session.user_id or "unknown",
        )

        async for run_event in self._scaffold.run(spec, spec.run_id):
            yield DeepCodeEvent(
                event_type=run_event.event_type,
                message=run_event.message,
                details=run_event.details,
                user_id=session.user_id,
                project_id=session.project_id,
                session_id=session_id,
            )

        session.status = "completed"
        session.updated_at = datetime.utcnow().isoformat()

    def resume_session(self, session_id: str) -> DeepCodeSession:
        session = self._sessions.get(session_id)
        if not session:
            raise ValueError(f"Session {session_id} not found")
        session.status = "idle"
        session.updated_at = datetime.utcnow().isoformat()
        return session
