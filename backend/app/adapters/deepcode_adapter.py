"""
Prototype Scaffold Adapter — labelled fixed-file scaffold fallback.

This adapter generates a fixed Python starter project regardless of the prompt.
It is NOT DeepCode execution. It must NEVER be silently substituted for the
real DeepCode runtime. Users see "Prototype Scaffold" as the provider label
on every BuildRun produced by this adapter.
"""

import asyncio
import logging
import os
import re
import uuid
from datetime import datetime
from typing import AsyncGenerator, Dict, Optional

from app.adapters.coding_agent_adapter import CodingAgentAdapter
from app.models.build_models import BuildRunEvent, BuildSpec
from app.models.deepcode_models import (
    DeepCodeEvent,
    DeepCodeSession,
    DeepCodeStep,
)

logger = logging.getLogger("backend.prototype_scaffold_adapter")


class PrototypeScaffoldAdapter(CodingAgentAdapter):
    """
    Explicitly labelled scaffold-only fallback. Must NEVER be described
    as genuine DeepCode execution.
    """

    @property
    def provider_label(self) -> str:
        return "prototype_scaffold"

    async def run(
        self,
        spec: BuildSpec,
        run_id: str,
    ) -> AsyncGenerator[BuildRunEvent, None]:
        workspace = os.path.abspath(os.path.normpath(spec.workspace_path))
        os.makedirs(workspace, exist_ok=True)

        seq = 0

        def _evt(event_type: str, message: str, **details) -> BuildRunEvent:
            nonlocal seq
            seq += 1
            return BuildRunEvent(
                run_id=run_id,
                sequence=seq,
                event_type=event_type,
                message=message,
                details=details,
                provider=self.provider_label,
            )

        yield _evt("start", f"[Prototype Scaffold] Starting scaffold for run {run_id}")
        await asyncio.sleep(0.05)

        workspace_name = os.path.basename(workspace) or "generated_project"
        package_name = re.sub(r"[^a-zA-Z0-9_]", "_", workspace_name.lower()).strip("_") or "generated_project"
        if package_name[0].isdigit():
            package_name = f"project_{package_name}"

        prompt = spec.specification

        def write_file(rel_path: str, content: str) -> None:
            full_path = os.path.join(workspace, rel_path)
            parent = os.path.dirname(full_path)
            if parent:
                os.makedirs(parent, exist_ok=True)
            with open(full_path, "w", encoding="utf-8") as fh:
                fh.write(content)

        files = {
            "project_spec.md": (
                f"# Project Blueprint & Specification\n\n"
                f"**Prompt:** {prompt}\n"
                "**Generated By:** Soul Build Mode (Prototype Scaffold)\n"
                "**Status:** Active\n\n"
                "## Specification Details\n"
                f"- Target Workspace: `{workspace}`\n"
                f"- Python Package: `{package_name}`\n"
            ),
            "README.md": (
                f"# {workspace_name.replace('_', ' ').title()}\n\n"
                "This project scaffold was generated by Soul Build Mode (Prototype Scaffold).\n\n"
                f"## Original request\n{prompt}\n"
            ),
            ".gitignore": "__pycache__/\n*.pyc\n.pytest_cache/\n.venv/\n.env\n",
            "pyproject.toml": (
                "[project]\n"
                f'name = "{package_name.replace("_", "-")}"\n'
                'version = "0.1.0"\n'
                'description = "Generated by Soul Build Mode (Prototype Scaffold)"\n'
                'requires-python = ">=3.11"\n\n'
                "[tool.pytest.ini_options]\n"
                'testpaths = ["tests"]\n'
            ),
            "main.py": (
                f"from src.{package_name}.app import main\n\n"
                "if __name__ == '__main__':\n"
                "    main()\n"
            ),
            os.path.join("src", package_name, "__init__.py"): '"""Generated application package."""\n',
            os.path.join("src", package_name, "app.py"): (
                f"PROMPT = {prompt!r}\n\n"
                "def build_summary() -> str:\n"
                '    return f"Soul generated scaffold for: {PROMPT}"\n\n'
                "def main() -> None:\n"
                "    print(build_summary())\n"
            ),
            os.path.join("tests", "test_app.py"): (
                f"from src.{package_name}.app import build_summary\n\n"
                "def test_build_summary_mentions_generated_scaffold():\n"
                "    summary = build_summary()\n"
                '    assert "Soul generated scaffold" in summary\n'
            ),
        }

        for rel_path, content in files.items():
            write_file(rel_path, content)
            yield _evt("file_create", f"Created {rel_path}", file=rel_path)
            await asyncio.sleep(0.05)

        yield _evt(
            "complete",
            f"[Prototype Scaffold] Generated {len(files)} files in {workspace}",
            generated_files=sorted(files.keys()),
        )

    async def cancel(self, run_id: str) -> None:
        logger.info("PrototypeScaffoldAdapter.cancel(%s) -- no-op (synchronous)", run_id)


